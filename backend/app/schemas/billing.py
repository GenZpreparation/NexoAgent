"""
NexoAgent - Billing & Razorpay Pydantic Schemas
Defines request and response schemas for Wallet recharges, Razorpay Orders, and Ledger entries.
"""
from datetime import datetime
from typing import Optional, List
from pydantic import BaseModel, Field


class CreateOrderRequest(BaseModel):
    amount_inr: float = Field(..., ge=100.0, le=500000.0, example=1000.0, description="Amount in INR")
    pack_id: Optional[str] = Field(default=None, example="growth_pack", description="starter, growth, scale, or custom")


class CreateOrderResponse(BaseModel):
    order_id: str = Field(..., example="order_EKwxwAgIt4212")
    amount_inr: float = Field(..., example=1000.0)
    amount_paise: int = Field(..., example=100000)
    currency: str = Field(default="INR", example="INR")
    receipt: str
    key_id: str
    status: str = "created"


class VerifyPaymentRequest(BaseModel):
    razorpay_order_id: str = Field(..., example="order_EKwxwAgIt4212")
    razorpay_payment_id: str = Field(..., example="pay_29QQoUBi66xmEy")
    razorpay_signature: str = Field(..., description="HMAC SHA-256 signature generated by Razorpay")
    amount_inr: float = Field(..., ge=100.0, example=1000.0)


class VerifyPaymentResponse(BaseModel):
    status: str = "payment_verified"
    credited_amount: float
    new_balance_inr: float
    transaction_id: int
    message: str


class WalletSummaryResponse(BaseModel):
    balance_inr: float
    currency: str = "INR"
    estimated_minutes_remaining: int
    rate_per_minute: float = 5.50
    is_low_balance: bool
    workspace_name: str


class TransactionItemResponse(BaseModel):
    id: int
    workspace_id: int
    transaction_type: str
    amount_inr: float
    opening_balance_inr: float
    closing_balance_inr: float
    reference_id: Optional[str]
    description: str
    created_at: datetime

    class Config:
        from_attributes = True
